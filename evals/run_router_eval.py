"""Router golden-set eval → docs/ROUTER_EVAL.md (DESIGN.md §5.3).

Golden-set format (one JSON object per line):
    {"prompt": str, "expected_tier": "cheap"|"standard"|"premium", "reasoning": str}

The reasoning field is the labeler's justification per the rubric — it rides
into the misclassification table, so every error row shows WHY a human chose
that tier. That is what makes the numbers defensible instead of vibes.

Pure: no HTTP, no Redis, no model — deterministic rules, milliseconds.
`make eval`. Regenerate and COMMIT docs/ROUTER_EVAL.md after any
keywords.yaml change; a stale eval is worse than none.
"""

from __future__ import annotations

import json
from collections import Counter
from datetime import UTC, datetime
from pathlib import Path

from llm_gateway.config import Tier
from llm_gateway.router.classifier import RuleBasedClassifier
from llm_gateway.schemas.openai_api import ChatCompletionRequest, Message

ROOT = Path(__file__).resolve().parents[1]
ORDER = [Tier.CHEAP, Tier.STANDARD, Tier.PREMIUM]


def parse_entries(path: Path) -> list[dict]:
    """Strict loader: a malformed line kills the run WITH ITS LINE NUMBER.

    Deliberate — a truncated final line (bad paste, editor cut) would otherwise
    silently vanish from the eval and every number downstream would be quietly
    wrong. Same fail-loud rule as everything else in this codebase."""
    entries: list[dict] = []
    seen: dict[str, int] = {}
    for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), start=1):
        if not line.strip():
            continue
        try:
            entry = json.loads(line)
        except json.JSONDecodeError as exc:
            raise SystemExit(f"{path.name}:{number}: not valid JSON — {exc}") from exc
        missing = {"prompt", "expected_tier"} - entry.keys()
        if missing:
            raise SystemExit(f"{path.name}:{number}: missing {sorted(missing)}")
        if entry["expected_tier"] not in {t.value for t in ORDER}:
            raise SystemExit(f"{path.name}:{number}: bad expected_tier {entry['expected_tier']!r}")
        if entry["prompt"] in seen:
            print(f"warning: duplicate prompt at lines {seen[entry['prompt']]} and {number}")
        else:
            seen[entry["prompt"]] = number
        entries.append(entry)
    if not entries:
        raise SystemExit(f"{path}: no entries")
    return entries


def main() -> None:
    classifier = RuleBasedClassifier.from_yaml(ROOT / "data" / "keywords.yaml")
    entries = parse_entries(ROOT / "evals" / "golden_set.jsonl")

    confusion = {e: {g: 0 for g in ORDER} for e in ORDER}
    errors: list[dict] = []
    for entry in entries:
        request = ChatCompletionRequest(
            model="auto", messages=[Message(role="user", content=entry["prompt"])]
        )
        decision = classifier.classify(request)
        expected, got = Tier(entry["expected_tier"]), decision.tier
        confusion[expected][got] += 1
        if expected != got:
            errors.append(
                {
                    "prompt": entry["prompt"],
                    "expected": expected.value,
                    "got": got.value,
                    "rule_fired": decision.rule_fired,
                    "reasoning": entry.get("reasoning", ""),
                }
            )

    # Per-tier precision/recall/F1 + macro F1.
    stats, f1s = {}, []
    for tier in ORDER:
        tp = confusion[tier][tier]
        predicted = sum(confusion[e][tier] for e in ORDER)
        actual = sum(confusion[tier].values())
        precision = tp / predicted if predicted else 0.0
        recall = tp / actual if actual else 0.0
        f1 = 2 * precision * recall / (precision + recall) if precision + recall else 0.0
        stats[tier] = (precision, recall, f1)
        f1s.append(f1)
    macro = sum(f1s) / len(f1s)

    # Error directions — where the iterate loop should look first.
    directions = Counter((e["expected"], e["got"]) for e in errors)

    # ── terminal summary ──
    print(f"\n{len(entries)} prompts · macro F1 = {macro:.3f} · {len(errors)} errors\n")
    print(f"{'tier':<10}{'precision':>10}{'recall':>9}{'f1':>7}{'support':>9}")
    for tier in ORDER:
        p, r, f1 = stats[tier]
        print(f"{tier.value:<10}{p:>10.2f}{r:>9.2f}{f1:>7.2f}{sum(confusion[tier].values()):>9}")
    if directions:
        print("\ntop error directions (expected → got):")
        for (e, g), count in directions.most_common(6):
            print(f"  {e} → {g}: {count}")
    print("\ndetails → docs/ROUTER_EVAL.md\n")

    # ── docs/ROUTER_EVAL.md ──
    lines = [
        "# Router evaluation",
        "",
        f"_Generated by `make eval` on {datetime.now(UTC).date()} — {len(entries)} prompts, "
        f"each hand-labeled per [labeling_rubric.md](../evals/labeling_rubric.md) with a "
        f"per-prompt reasoning note in [golden_set.jsonl](../evals/golden_set.jsonl)._",
        "",
        "## Confusion matrix (rows = expected, columns = predicted)",
        "",
        "| | " + " | ".join(t.value for t in ORDER) + " |",
        "|---|" + "---|" * len(ORDER),
    ]
    for e in ORDER:
        lines.append(f"| **{e.value}** | " + " | ".join(str(confusion[e][g]) for g in ORDER) + " |")
    lines += [
        "",
        "## Per-tier metrics",
        "",
        "| tier | precision | recall | F1 | support |",
        "|---|---|---|---|---|",
    ]
    for tier in ORDER:
        p, r, f1 = stats[tier]
        lines.append(
            f"| {tier.value} | {p:.2f} | {r:.2f} | {f1:.2f} | {sum(confusion[tier].values())} |"
        )
    lines += ["", f"**Macro F1: {macro:.3f}**", ""]

    if errors:
        lines += [
            "## Error directions",
            "",
            "| expected → got | count |",
            "|---|---|",
        ]
        for (e, g), count in directions.most_common():
            lines.append(f"| {e} → {g} | {count} |")
        lines += [
            "",
            "## Misclassification analysis",
            "",
            "| prompt | expected | got | rule fired | labeler's reasoning |",
            "|---|---|---|---|---|",
        ]
        for err in errors[:25]:
            lines.append(
                f"| {err['prompt'][:90]} | {err['expected']} | {err['got']} "
                f"| {err['rule_fired']} | {err['reasoning'][:110]} |"
            )
        if len(errors) > 25:
            lines.append(f"| _…{len(errors) - 25} more_ | | | | |")
        lines += [
            "",
            "**Reading the errors:** the dominant direction is cheap↔standard confusion on",
            "short technical 'What is X?' prompts — the rule engine cannot see domain depth",
            "('What is a thread?' vs 'What is Raft?'), only surface signals. That is the",
            "documented ADR-0001 underfit, now quantified. Each row is either a",
            "keywords.yaml fix, a `not_keywords` guard, or an accepted-and-documented",
            "limitation; the `X-Routing-Strategy` header is the per-request escape hatch.",
        ]
    else:
        lines += [
            "_No misclassifications on this set — suspicious. Either the set is too easy",
            "or it was labeled to match the router. Extend with harder adversarial pairs._",
        ]

    out = ROOT / "docs" / "ROUTER_EVAL.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
